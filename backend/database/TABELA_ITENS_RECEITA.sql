CREATE TABLE ITENS_RECEITA(
	IDITENSRECEITA		UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	IDRECEITA			UUID NOT NULL REFERENCES RECEITA(IDRECEITA) ON DELETE CASCADE,
	IDMEDICAMENTO		UUID NOT NULL REFERENCES MEDICAMENTO(IDMEDICAMENTO),
	DOSE				VARCHAR(50),
	INTERVALO_HORAS		SMALLINT NOT NULL CHECK (INTERVALO_HORAS > 0),
	DURACAO_DIAS		SMALLINT NOT NULL CHECK (DURACAO_DIAS > 0),
	DATA_INICIO			TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	QUANTIDADE_ALERTA 	SMALLINT GENERATED ALWAYS AS (CEIL((DURACAO_DIAS * 24.0) / INTERVALO_HORAS)) STORED,
	STATUS				STATUS_ITEM_RECEITA NOT NULL DEFAULT 'AGUARDANDO_CONFIRMACAO');