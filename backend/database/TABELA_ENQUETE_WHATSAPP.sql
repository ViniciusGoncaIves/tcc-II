CREATE TABLE ENQUETE_WHATSAPP(
	IDENQUETE			UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	ID_MENSAGEM			VARCHAR(100) NOT NULL UNIQUE,
	TIPO				TIPO_ENQUETE NOT NULL,
	IDPACIENTE			UUID NOT NULL REFERENCES PACIENTE(IDPACIENTE),
	IDALERTA			UUID REFERENCES ALERTA(IDALERTA),
	DESTINO				VARCHAR(100) NOT NULL,
	CONTEUDO			TEXT NOT NULL,
	DATA_ENVIO			TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CHECK((TIPO = 'CONFIRMACAO_DOSE') = (IDALERTA IS NOT NULL)));