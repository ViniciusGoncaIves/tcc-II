-- Aplica a integração com o WhatsApp num banco criado antes dela (rodar uma única vez).
-- Bancos novos já nascem assim pelos scripts de criação.
BEGIN;

CREATE TYPE MOTIVO_CANCELAMENTO AS ENUM ('USUARIO', 'PRIMEIRA_DOSE_NAO_CONFIRMADA', 'PEDIDO_DO_PACIENTE');
CREATE TYPE MOTIVO_INATIVACAO AS ENUM ('USUARIO', 'PEDIDO_DO_PACIENTE');
CREATE TYPE TIPO_ENQUETE AS ENUM ('CONFIRMACAO_DOSE', 'CONFIRMACAO_PARADA');

ALTER TABLE PACIENTE ADD COLUMN MOTIVO_INATIVACAO MOTIVO_INATIVACAO;
UPDATE PACIENTE
   SET MOTIVO_INATIVACAO = 'USUARIO'
 WHERE PACIENTE.ATIVO = FALSE;

-- Receitas canceladas antes: com usuário, por um usuário; sem usuário, pelo sistema (dose 1 expirada).
ALTER TABLE RECEITA ADD COLUMN MOTIVO_CANCELAMENTO MOTIVO_CANCELAMENTO;
UPDATE RECEITA
   SET MOTIVO_CANCELAMENTO = CASE
                               WHEN RECEITA.USUARIO_CANCELAMENTO IS NULL
                               THEN 'PRIMEIRA_DOSE_NAO_CONFIRMADA'::MOTIVO_CANCELAMENTO
                               ELSE 'USUARIO'::MOTIVO_CANCELAMENTO
                             END
 WHERE RECEITA.STATUS = 'CANCELADA';

CREATE TABLE ENQUETE_WHATSAPP(
	IDENQUETE			UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	ID_MENSAGEM			VARCHAR(100) NOT NULL UNIQUE,
	TIPO				TIPO_ENQUETE NOT NULL,
	IDPACIENTE			UUID NOT NULL REFERENCES PACIENTE(IDPACIENTE),
	IDALERTA			UUID REFERENCES ALERTA(IDALERTA),
	DESTINO				VARCHAR(100) NOT NULL,
	CONTEUDO			TEXT NOT NULL,
	DATA_ENVIO			TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	CHECK((TIPO = 'CONFIRMACAO_DOSE') = (IDALERTA IS NOT NULL)));

COMMIT;
