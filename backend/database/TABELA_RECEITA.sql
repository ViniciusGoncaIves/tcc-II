CREATE TABLE RECEITA(
	IDRECEITA			UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	IDPACIENTE			UUID NOT NULL REFERENCES PACIENTE(IDPACIENTE),
	USUARIO				UUID NOT NULL REFERENCES USUARIO(IDUSUARIO),
	OBSERVACAO			TEXT,
	STATUS				STATUS_RECEITA NOT NULL DEFAULT 'ATIVA',
	DATA_EMISSAO		TIMESTAMPTZ NOT NULL DEFAULT NOW(),
	DATA_CANCELAMENTO	TIMESTAMPTZ,
	USUARIO_CANCELAMENTO	UUID REFERENCES USUARIO(IDUSUARIO));