CREATE TABLE ALERTA(
	IDALERTA				UUID PRIMARY KEY DEFAULT GEN_RANDOM_UUID(),
	IDITENSRECEITA			UUID NOT NULL REFERENCES ITENS_RECEITA(IDITENSRECEITA) ON DELETE CASCADE,
	NUMERO_DOSE				SMALLINT NOT NULL,
	REQUER_CONFIRMACAO		BOOLEAN NOT NULL DEFAULT FALSE,
	HORARIO_PREVISTO		TIMESTAMPTZ NOT NULL,
	HORARIO_ENVIO			TIMESTAMPTZ,
	HORARIO_CONFIRMACAO		TIMESTAMPTZ,
	STATUS					STATUS_ALERTA NOT NULL DEFAULT 'PENDENTE',
	TENTATIVAS				SMALLINT NOT NULL DEFAULT 0,
	LIMITE_TENTATIVAS		SMALLINT NOT NULL DEFAULT 3,
	PROXIMA_TENTATIVA		TIMESTAMPTZ,
	UNIQUE(IDITENSRECEITA, NUMERO_DOSE),
	CHECK(TENTATIVAS <= LIMITE_TENTATIVAS));